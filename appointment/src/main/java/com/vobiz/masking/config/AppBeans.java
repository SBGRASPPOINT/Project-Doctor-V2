import com.vobiz.masking.appointment.service.AppointmentIvrService;
import com.vobiz.masking.appointment.service.AppointmentService;
import com.vobiz.masking.appointment.service.AvailabilityService;
import com.vobiz.masking.appointment.service.DepartmentService;
import com.vobiz.masking.appointment.service.DoctorService;
import com.vobiz.masking.appointment.service.PatientDirectoryService;
import com.vobiz.masking.appointment.service.PromptService;
import com.vobiz.masking.appointment.service.ReminderService;
import com.vobiz.masking.appointment.service.ScheduleService;
import com.vobiz.masking.appointment.service.SmsService;
import com.vobiz.masking.repo.AgentDao;
import com.vobiz.masking.repo.AgentRepository;
import com.vobiz.masking.security.WebhookSigner;
import com.vobiz.masking.repo.CallDao;
import com.vobiz.masking.repo.CallRepository;
import com.vobiz.masking.repo.CallbackDao;
import com.vobiz.masking.repo.CallbackRepository;
import com.vobiz.masking.repo.SettingRepository;
import com.vobiz.masking.repo.SettingsDao;
import com.vobiz.masking.service.AgentService;
import com.vobiz.masking.service.CallFlowService;
import com.vobiz.masking.service.CallbackService;
import com.vobiz.masking.service.RoutingService;
import com.vobiz.masking.service.SettingsService;
import com.vobiz.masking.vobiz.VobizClient;
import com.vobiz.masking.vobiz.VobizWhatsAppClient;
import com.vobiz.masking.whatsapp.WhatsAppService;
import com.vobiz.masking.whatsapp.WhatsAppTransport;
import com.vobiz.masking.whatsapp.repo.WhatsAppConversationRepository;
import com.vobiz.masking.whatsapp.repo.WhatsAppMessageRepository;
import com.vobiz.masking.whatsapp.repo.WhatsAppStaffAccessRepository;
import com.vobiz.masking.whatsapp.security.WhatsAppAccessService;
import com.vobiz.masking.web.Handlers;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.boot.context.properties.EnableConfigurationProperties;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * Composition root. Spring Boot auto-configures the DataSource (HikariCP + PostgreSQL
 * driver), the JPA repositories (both packages) and the {@link JdbcTemplate}; everything
 * below them is plain Java and unit-testable as such. The database schema itself is
 * generated by Hibernate from the {@code @Entity} classes — there is no schema.sql.
 */
@Configuration
@EnableConfigurationProperties({AppProperties.class, VobizProperties.class})
public class AppBeans {

    private static final Logger log = LogManager.getLogger(AppBeans.class);

    /** Signs every URL handed to Vobiz so AuthFilter can tell real webhooks from made-up ones. */
    @Bean
    WebhookSigner webhookSigner(AppProperties app) {
        WebhookSigner signer = new WebhookSigner(app.getWebhookSecret());
        if (!signer.isEnabled())
            log.warn("app.webhook-secret is empty — /voice/** webhooks are UNSIGNED (development only)");
        if (app.getApiToken() == null || app.getApiToken().isBlank())
            log.warn("app.api-token is empty — /api/** is UNAUTHENTICATED (development only)");
        return signer;
    }

    @Bean
    WebhookSigner vobizWhatsappWebhookSigner(VobizProperties properties) {
        return new WebhookSigner(properties.getWhatsappWebhookSecret());
    }

    // ---------- masking core (unchanged) ----------

    @Bean
    SettingsDao settingsDao(SettingRepository repo) {
        return new SettingsDao(repo);
    }

    @Bean
    AgentDao agentDao(AgentRepository repo) {
        return new AgentDao(repo);
    }

    @Bean
    CallDao callDao(CallRepository repo, JdbcTemplate jdbc) {
        return new CallDao(repo, jdbc);
    }

    @Bean
    CallbackDao callbackDao(CallbackRepository repo, AgentRepository agentRepo, JdbcTemplate jdbc) {
        return new CallbackDao(repo, agentRepo, jdbc);
    }

    @Bean
    SettingsService settingsService(SettingsDao dao) {
        return new SettingsService(dao);
    }

    @Bean
    RoutingService routingService(AgentDao agentDao, SettingsDao settingsDao) {
        return new RoutingService(agentDao, settingsDao);
    }

    @Bean
    VobizClient vobizClient(VobizProperties props) {
        return new VobizClient(props.getAuthId(), props.getAuthToken(), props.getApiBase(), props.isMock());
    }

    @Bean
    CallFlowService callFlowService(CallDao callDao, CallbackDao callbackDao, SettingsService settings,
                                    RoutingService routing, AppProperties app,
                                    @Qualifier("webhookSigner") WebhookSigner signer) {
        return new CallFlowService(callDao, callbackDao, settings, routing,
                trimSlash(app.getPublicBaseUrl()), app.getDefaultM1Number(), signer);
    }

    @Bean
    AgentService agentService(AgentDao agentDao) {
        return new AgentService(agentDao);
    }

    @Bean
    CallbackService callbackService(CallbackDao callbackDao, AgentDao agentDao, RoutingService routing,
                                    CallDao callDao, SettingsService settings, VobizClient vobiz, AppProperties app,
                                    @Qualifier("webhookSigner") WebhookSigner signer) {
        return new CallbackService(callbackDao, agentDao, routing, callDao, settings, vobiz,
                trimSlash(app.getPublicBaseUrl()), app.getDefaultM1Number(), signer);
    }

    // ---------- appointment domain ----------

    @Bean
    AppointmentDao appointmentDao(AppointmentRepository repo, JdbcTemplate jdbc) {
        return new AppointmentDao(repo, jdbc);
    }

    @Bean
    ReminderDao reminderDao(ReminderRepository repo, JdbcTemplate jdbc) {
        return new ReminderDao(repo, jdbc);
    }

    @Bean
    PromptService promptService(MessageTemplateRepository repo) {
        return new PromptService(repo);
    }

    @Bean
    AvailabilityService availabilityService(DoctorRepository doctorRepo, DoctorScheduleRepository scheduleRepo,
                                            DoctorTimeOffRepository timeOffRepo, AppointmentRepository appointmentRepo,
                                            SettingsService settings) {
        return new AvailabilityService(doctorRepo, scheduleRepo, timeOffRepo, appointmentRepo, settings);
    }

    @Bean
    ReminderService reminderService(ReminderRepository reminderRepo, AppointmentRepository appointmentRepo,
                                    AppointmentEventRepository eventRepo, PatientRepository patientRepo,
                                    CallDao callDao, VobizClient vobiz, SettingsService settings,
                                    AppProperties app, @Qualifier("webhookSigner") WebhookSigner signer,
                                    SmsService smsService) {
        return new ReminderService(reminderRepo, appointmentRepo, eventRepo, patientRepo, callDao, vobiz,
                settings, app, signer, smsService);
    }

    @Bean
    AppointmentService appointmentService(AppointmentRepository appointmentRepo, AppointmentEventRepository eventRepo,
                                          PatientRepository patientRepo, DoctorRepository doctorRepo,
                                          AvailabilityService availability, ReminderService reminders,
                                          SettingsService settings) {
        return new AppointmentService(appointmentRepo, eventRepo, patientRepo, doctorRepo,
                availability, reminders, settings);
    }

    @Bean
    PatientDirectoryService patientDirectoryService(PatientRepository repo) {
        return new PatientDirectoryService(repo);
    }

    @Bean
    DepartmentService departmentService(DepartmentRepository repo) {
        return new DepartmentService(repo);
    }

    @Bean
    DoctorService doctorService(DoctorRepository repo) {
        return new DoctorService(repo);
    }

    @Bean
    ScheduleService scheduleService(DoctorScheduleRepository scheduleRepo, DoctorTimeOffRepository timeOffRepo,
                                    DoctorRepository doctorRepo, AppointmentRepository appointmentRepo,
                                    ReminderService reminderService, SettingsService settings) {
        return new ScheduleService(scheduleRepo, timeOffRepo, doctorRepo, appointmentRepo, reminderService, settings);
    }

    /** SMS fallback seam — no-op logger until a provider is wired (voice is the primary channel). */
    @Bean
    SmsService smsService() {
        return (phone, text) -> log.info("[SMS stub] to={} text={}", phone, text);
    }

    @Bean
    AppointmentIvrService appointmentIvrService(IvrSessionRepository sessions, PatientDirectoryService patients,
                                                DepartmentRepository departments, DoctorRepository doctors,
                                                AvailabilityService availability, AppointmentService appointments,
                                                ReminderService reminders, SettingsService settings,
                                                PromptService prompts, CallFlowService callFlow, CallDao callDao,
                                                AppProperties app,
                                                @Qualifier("webhookSigner") WebhookSigner signer) {
        return new AppointmentIvrService(sessions, patients, departments, doctors, availability, appointments,
                reminders, settings, prompts, callFlow, callDao, trimSlash(app.getPublicBaseUrl()), signer);
    }

    // ---------- shared WhatsApp inbox (Vobiz Messaging API; wired through DI) ----------

    @Bean
    WhatsAppTransport whatsappTransport(VobizProperties properties) {
        return new VobizWhatsAppClient(properties);
    }

    @Bean
    WhatsAppAccessService whatsappAccessService(WhatsAppStaffAccessRepository repository) {
        return new WhatsAppAccessService(repository);
    }

    @Bean
    WhatsAppService whatsappService(WhatsAppConversationRepository conversations,
                                    WhatsAppMessageRepository messages,
                                    WhatsAppTransport transport,
                                    VobizProperties properties,
                                    SettingsService settings,
                                    AppProperties app) {
        return new WhatsAppService(conversations, messages, transport, properties, settings, app);
    }

    // ---------- web ----------

    @Bean
    Handlers handlers(AgentService agentService, CallFlowService callFlow, CallbackService callbackService,
                      SettingsService settings, CallDao callDao, CallbackDao callbackDao,
                      AppointmentIvrService ivr, ReminderService reminders,
                      AppointmentDao appointmentDao, ReminderDao reminderDao,
                      AppointmentService appointmentService, PatientDirectoryService patientDirectoryService,
                      DoctorService doctorService, DepartmentService departmentService,
                      ScheduleService scheduleService, AvailabilityService availabilityService,
                      AppointmentEventRepository eventRepo, MessageTemplateRepository templateRepo) {
        return new Handlers(agentService, callFlow, callbackService, settings, callDao, callbackDao,
                ivr, reminders, appointmentDao, reminderDao, appointmentService, patientDirectoryService,
                doctorService, departmentService, scheduleService, availabilityService, eventRepo, templateRepo);
    }

    private static String trimSlash(String url) {
        if (url == null) return "";
        return url.endsWith("/") ? url.substring(0, url.length() - 1) : url;
    }
}
